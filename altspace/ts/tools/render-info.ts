// Writes ts/render.json: what the kit builder (Assets/Kit/Editor/BrickKitBuilder.cs) needs from the TypeScript so that
// the Unity side and the script agree on numbers that travel between them:
//  - oris: the 24 cube rotations in wire order (Lattice.ORIS), as Unity quaternions (x, y, z, w);
//  - bricks: per type number, the prefab name, the mesh files, and where an uncovered stud sits on the placed body
//    (mesh metres, brick space; from the male connectors' mate points, as BrickAttach.RecalculateRenderedGeometry
//    places the `Studs` children), and the chunk renderer's mesh index base (1 + 4 * type; 0 is the empty mesh).
//
//   node --disable-warning=ExperimentalWarning tools/render-info.ts      (npm run render-info)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BRICKS, CATEGORIES } from "../src/BrickData.ts";
import { MESH_M_PER_U, ORIS } from "../src/Lattice.ts";
import { MESH_VARIANTS } from "../src/BrickRenderer.ts";

/** README of tools/bricks: the modular Stud.fbx pivot sits 0.2 mm above the top face it stands on. */
const STUD_PIVOT_ABOVE_TOP = 0.0002;

const round = (v: number) => Math.round(v * 1e7) / 1e7;
const out = {
  _doc: "Generated by ts/tools/render-info.ts (npm run render-info). Read by Assets/Kit/Editor/BrickKitBuilder.cs.",
  variants: MESH_VARIANTS,
  categories: CATEGORIES,
  oris: ORIS.map((o) => o.q.map(round)),
  bricks: BRICKS.map((b) => ({
    type: b.type,
    prefab: b.prefab,
    display: b.display,
    category: b.category,
    picker: b.picker,
    complete: b.meshes.complete,
    files: b.meshes.files,
    size: b.size,
    heightPlates: b.heightPlates,
    bottomPlates: b.bottomPlates,
    // only studs on top (+Y): side studs exist only in the Complete meshes, which the renderer then uses as they are
    studs: b.males.filter((c) => c.up[1] === 1).map((c) => [round(c.mate[0] * MESH_M_PER_U), round(c.mate[1] * MESH_M_PER_U + STUD_PIVOT_ABOVE_TOP), round(c.mate[2] * MESH_M_PER_U)]),
    sideStuds: b.males.some((c) => c.up[1] !== 1),
    heldBoxes: b.heldBoxes.map((h) => ({ c: h.c.map((v) => round(v * 7 * MESH_M_PER_U)), size: h.h.map((v) => round(2 * v * 7 * MESH_M_PER_U)), q: h.q })),
  })),
};
const path = fileURLToPath(new URL("../render.json", import.meta.url));
writeFileSync(path, JSON.stringify(out, null, 1) + "\n");
console.log(`render.json: ${out.bricks.length} bricks, ${out.oris.length} orientations`);
